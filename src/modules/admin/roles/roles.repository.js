const { query, pool } = require("../../../config/db");

//----------------------------------------------------------------------------------------------------------------------------------------
// ADD NEW ROLE
//----------------------------------------------------------------------------------------------------------------------------------------

async function addNewRole() {
  const SQL = "INSERT INTO roles () VALUES () RETURNING *";

  const roles = await query(SQL, []);

  return roles.rows[0];
}

//----------------------------------------------------------------------------------------------------------------------------------------
// FETCH ROLES
//----------------------------------------------------------------------------------------------------------------------------------------

async function fetchAllRoles() {
  const SQL = "SELECT * FROM roles";
  const roles = await query(SQL);
  return roles.rows;
}

